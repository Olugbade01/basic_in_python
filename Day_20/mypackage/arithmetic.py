def add_numbers(*args):
    total = 0
    for num in args:
        total += num
    return total

def subtract(x,y):
    return (x - y)

def multiply(x, y):
    return (x*y)

def division(x, y):
    return (x/y)

def remainder(x, y):
    return (x%y)

def power(x,y):
    return (x ** y)
